# ---- classification metrics (horizontal = positive class) ----------------------------------------------------
def metrics(y, out):
    pred = np.where(out > 0, 1, -1)
    tp = int(np.sum((pred == 1) & (y == 1))); tn = int(np.sum((pred == -1) & (y == -1)))
    fp = int(np.sum((pred == 1) & (y == -1))); fn = int(np.sum((pred == -1) & (y == 1)))
    prec = tp / (tp + fp) if tp + fp else float("nan")
    rec = tp / (tp + fn) if tp + fn else float("nan")
    f1 = 2 * prec * rec / (prec + rec) if prec + rec else float("nan")
    return dict(tp=tp, tn=tn, fp=fp, fn=fn, acc=(tp + tn) / len(y), prec=prec, rec=rec, f1=f1)


