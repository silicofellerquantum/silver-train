# four-term rule for a controlled rotation (generator eigenvalues 0, +-1/2).
# Hadamard test: control in |+>, controlled-RZ, H on the control, measure Z on the control:
# <Z_0> = Re <phi|R_Z(t)|phi> = cos(t/2) (pure frequency 1/2) for any target state |phi>.
@cudaq.kernel
def crz_demo(t: float):
    q = cudaq.qvector(2)
    h(q[0]); ry(0.7, q[1])
    rx(0.4, q[1])
    rz.ctrl(t, q[0], q[1])
    h(q[0])


XX = cudaq.spin.z(0)
g = lambda t: cudaq.observe(crz_demo, XX, float(t)).expectation()
tc = 0.9
fd_c = (g(tc + 1e-5) - g(tc - 1e-5)) / 2e-5
two_c = (g(tc + np.pi / 2) - g(tc - np.pi / 2)) / 2
dp, dm = (np.sqrt(2) + 1) / (4 * np.sqrt(2)), (np.sqrt(2) - 1) / (4 * np.sqrt(2))
four_c = dp * (g(tc + np.pi / 2) - g(tc - np.pi / 2)) - dm * (g(tc + 3 * np.pi / 2) - g(tc - 3 * np.pi / 2))
num("crzfd", f"{fd_c:+.4f}"); num("crztwo", f"{two_c:+.4f}"); num("crzfour", f"{four_c:+.4f}")
print("controlled-RZ gradient: fd", fd_c, "two-term", two_c, "four-term", four_c)


# ---- 2d. barren plateaus: hardware-efficient ansatz vs QCNN ------------------------------------------------
@cudaq.kernel
def hea(n: int, depth: int, theta: list[float]):
    q = cudaq.qvector(n)
    for i in range(n):
        ry(np.pi / 4, q[i])
    for l in range(depth):
        for i in range(n):
            ry(theta[2 * n * l + i], q[i])
            rz(theta[2 * n * l + n + i], q[i])
        for i in range(n - 1):
            z.ctrl(q[i], q[i + 1])


def global_z(n):
    op = cudaq.spin.z(0)
    for i in range(1, n):
        op = op * cudaq.spin.z(i)
    return op


bp_rng = np.random.default_rng(11)
SIZES = [2, 4, 6, 8, 10]
SAMPLES = 200
var_glob, var_loc, var_qcnn = [], [], []
for n in SIZES:
    depth = 2 * n
    ops = (global_z(n), cudaq.spin.z(0) * cudaq.spin.z(1))
    grads = [[], []]
    for _ in range(SAMPLES):
        th = bp_rng.uniform(0, 2 * np.pi, 2 * n * depth)
        for k, op in enumerate(ops):
            plus, minus = th.copy(), th.copy()
            plus[0] += np.pi / 2; minus[0] -= np.pi / 2
            grads[k].append((cudaq.observe(hea, op, n, depth, list(plus)).expectation()
                             - cudaq.observe(hea, op, n, depth, list(minus)).expectation()) / 2)
    var_glob.append(np.var(grads[0])); var_loc.append(np.var(grads[1]))
QSIZES = [4, 6, 8, 10, 12]
for n in QSIZES:
    lay = qcnn_layout(n)
    ro = cudaq.spin.z(lay[4])
    gr = []
    for _ in range(100):
        th = bp_rng.uniform(0, 2 * np.pi, 4 * lay[5])
        px = list(bp_rng.uniform(0, 1, n))
        e = np.zeros(len(th)); e[0] = 1e-4
        gr.append((cudaq.observe(qcnn, ro, px, list(th + e), *lay[:4]).expectation()
                   - cudaq.observe(qcnn, ro, px, list(th - e), *lay[:4]).expectation()) / 2e-4)
    var_qcnn.append(np.var(gr))
num("varglobten", f"{var_glob[-1]:.1e}"); num("varlocten", f"{var_loc[-1]:.1e}")
num("varqcnntwelve", f"{var_qcnn[-1]:.1e}")
print("barren plateau variances:", var_glob, var_loc, var_qcnn)

fig, ax = plt.subplots(figsize=(5.6, 2.8))
ax.semilogy(SIZES, var_glob, "o-", color=ORANGE, label=r"HEA, global cost $Z^{\otimes n}$ (depth $2n$)")
ax.semilogy(SIZES, var_loc, "s-", color=BLUE, label=r"HEA, local cost $Z_0Z_1$ (depth $2n$)")
ax.semilogy(QSIZES, var_qcnn, "^-", color=AQUA, label=r"QCNN of QML.ipynb, $\langle Z_{\rm out}\rangle$")
ax.semilogy(SIZES, [2.0 ** -n for n in SIZES], ":", color=GREY, label=r"$2^{-n}$ reference")
ax.set_xlabel("number of qubits $n$"); ax.set_ylabel(r"Var$[\partial_{\theta_1} f]$ (random $\theta$)")
ax.legend(fontsize=7)
save(fig, "barren_plateau")

