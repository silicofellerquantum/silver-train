# ---- 2c. parameter-shift rule ----------------------------------------------------------------------------
@cudaq.kernel
def vqc2(x0: float, x1: float, theta: list[float]):
    q = cudaq.qvector(2)
    ry(x0, q[0]); ry(x1, q[1])                    # angle encoding
    ry(theta[0], q[0]); ry(theta[1], q[1])        # trainable layer
    x.ctrl(q[0], q[1])
    ry(theta[2], q[1])


Z1 = cudaq.spin.z(1)
xs = (0.4, 1.1)


def f_vqc(th):
    return cudaq.observe(vqc2, Z1, xs[0], xs[1], [float(v) for v in th]).expectation()


th0 = np.array([0.3, -0.7, 0.5])
ps_grad, fd_grad = [], []
