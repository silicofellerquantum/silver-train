# ---- 2f. depolarising gate noise (density-matrix simulator) -----------------------------------------------
cudaq.set_target("density-matrix-cpu")
noise_rows = []
for p in (0.0, 0.01, 0.03, 0.1):
    nm = cudaq.NoiseModel()
    if p > 0:
        for gname in ("ry", "x"):
            nm.add_all_qubit_channel(gname, cudaq.DepolarizationChannel(p))
        for gname in ("x", "rz", "rx"):
            nm.add_all_qubit_channel(gname, cudaq.Depolarization2(p), num_controls=1)
    o = np.array([cudaq.observe(qcnn, readout, list(im), list(theta_trained), *LAY, noise_model=nm).expectation()
                  for im in test_x])
    noise_rows.append((p, np.mean(np.sign(o) == test_y), np.mean(np.abs(o)), np.mean((o - test_y) ** 2)))
cudaq.set_target("qpp-cpu")
write_table("noise_table", "rccc", r"$p$ & accuracy & mean $|\langle Z\rangle|$ & MSE",
            [f"{p:g} & {100 * acc:.0f}\\,\\% & {mag:.3f} & {mse:.3f}" for p, acc, mag, mse in noise_rows])
print("noise:", noise_rows)

