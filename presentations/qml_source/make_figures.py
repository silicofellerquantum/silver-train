def svm_dual(K, y, C=10.0):
    """Soft-margin SVM dual solved with SLSQP (small problem)."""
    n = len(y)
    Q = (y[:, None] * y[None, :]) * K
    fun = lambda a: 0.5 * a @ Q @ a - a.sum()
    jac = lambda a: Q @ a - 1
    cons = {"type": "eq", "fun": lambda a: a @ y, "jac": lambda a: y.astype(float)}
    a = minimize(fun, np.zeros(n), jac=jac, bounds=[(0, C)] * n, constraints=[cons], method="SLSQP").x
    sv = (a > 1e-6) & (a < C - 1e-6)
    b = np.mean(y[sv] - (a * y) @ K[:, sv]) if sv.any() else 0.0
    return a, b, int(np.sum(a > 1e-6))


alpha, bias, n_sv = svm_dual(K_tr, train_y.astype(float))
