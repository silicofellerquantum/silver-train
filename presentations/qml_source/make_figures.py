# ---- 2b. quantum kernel with the notebook's angle encoding --------------------------------------------------
@cudaq.kernel
def encode(pixels: list[float]):
    q = cudaq.qvector(len(pixels))
    for i in range(len(pixels)):
        ry(np.pi * pixels[i], q[i])


def states(images):
    return [np.array(cudaq.get_state(encode, list(im))) for im in images]


S_tr, S_te = states(train_x), states(test_x)
K_tr = np.array([[abs(np.vdot(a, b)) ** 2 for b in S_tr] for a in S_tr])
K_te = np.array([[abs(np.vdot(a, b)) ** 2 for b in S_tr] for a in S_te])


def analytic_kernel(A, B):
    return np.array([[np.prod(np.cos(np.pi * (a - b) / 2) ** 2) for b in B] for a in A])


kern_diff = max(np.max(np.abs(K_tr - analytic_kernel(train_x, train_x))),
                np.max(np.abs(K_te - analytic_kernel(test_x, train_x))))
