# ---- independent NumPy simulation of the same circuit (cross-check) ------------------------------------------
def ry_m(t):
    c, s = np.cos(t / 2), np.sin(t / 2)
    return np.array([[c, -s], [s, c]], complex)


def rx_m(t):
    c, s = np.cos(t / 2), np.sin(t / 2)
    return np.array([[c, -1j * s], [-1j * s, c]])


def rz_m(t):
    return np.diag([np.exp(-1j * t / 2), np.exp(1j * t / 2)])


X_M = np.array([[0, 1], [1, 0]], complex)


def apply1(psi, U, q):
    psi = np.tensordot(U, psi, axes=([1], [q]))
    return np.moveaxis(psi, 0, q)


def apply_c(psi, U, c, t):
    """Controlled-U (control c = 1)."""
    psi = psi.copy()
    idx = [slice(None)] * psi.ndim
    idx[c] = 1
    sub = psi[tuple(idx)]
    tt = t if t < c else t - 1
    sub = np.moveaxis(np.tensordot(U, sub, axes=([1], [tt])), 0, tt)
    psi[tuple(idx)] = sub
    return psi


def np_qcnn_z(pixels, theta, lay, outq):
    n = len(pixels)
    psi = np.zeros([2] * n, complex)
    psi[(0,) * n] = 1
    for i, p in enumerate(pixels):
        psi = apply1(psi, ry_m(np.pi * p), i)
    for kd, a, b, l in zip(*lay):
        t = 4 * l
        if kd == 0:
            psi = apply1(psi, ry_m(theta[t]), a)
            psi = apply1(psi, ry_m(theta[t + 1]), b)
            psi = apply_c(psi, X_M, a, b)
        else:
            psi = apply_c(psi, rz_m(theta[t + 2]), a, b)
            psi = apply1(psi, X_M, a)
            psi = apply_c(psi, rx_m(theta[t + 3]), a, b)
            psi = apply1(psi, X_M, a)
    p = np.abs(psi) ** 2
    p_out = p.sum(axis=tuple(i for i in range(n) if i != outq))
    return p_out[0] - p_out[1]


