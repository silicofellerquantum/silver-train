# ---- 2b. gate-level controlled multiplication for N = 15 -----------------------------------------------------
# work register w[0..3], w[0] = most significant bit (notebook convention).
# multiply by 2 mod 15 = cyclic left rotation of the 4 bits: (b3 b2 b1 b0) -> (b2 b1 b0 b3)
# multiply by 7 = multiply by 8 (three rotations) followed by NOT on every bit (7y = -8y mod 15),
# correct for 1 <= y <= 14 (all values reached from |1>); y = 0 and y = 15 are not used.
def mult_gates(a):
    rot = [("swap", 0, 1), ("swap", 1, 2), ("swap", 2, 3)]           # one left rotation
    k = {2: 1, 4: 2, 8: 3, 7: 3, 11: 2, 13: 1}[a]
    gates = rot * k
    if a in (7, 11, 13):
        gates += [("x", i) for i in range(4)]
    return gates


def perm_of(gates):
    out = []
    for y in range(16):
        bits = [(y >> (3 - i)) & 1 for i in range(4)]
        for g in gates:
            if g[0] == "swap":
                bits[g[1]], bits[g[2]] = bits[g[2]], bits[g[1]]
            else:
                bits[g[1]] ^= 1
        out.append(sum(b << (3 - i) for i, b in enumerate(bits)))
    return out


gl_ok = all(perm_of(mult_gates(a))[y] == a * y % 15 for a in (2, 4, 7, 8, 11, 13) for y in range(1, 15))
num("gatelevelok", "yes" if gl_ok else "NO")
print("2b gate-level multipliers agree with y -> a y mod 15 on 1..14:", gl_ok)


@cudaq.kernel
def shor15_gates(nt: int, ops: list[int], ctrl: list[int], qa: list[int], qb: list[int], idle: float):
    """Gate-level order finding for N = 15. ops: 0 = controlled SWAP via CNOT-Toffoli-CNOT, 1 = CNOT."""
    q = cudaq.qvector(nt + 4)                       # q[0..t-1] counting (q[0] = MSB of y), q[t..t+3] work (w0 = MSB)
    x(q[nt + 3])                                    # work register = |1>
    for i in range(nt):
        h(q[i])
    for k in range(len(ops)):
        c = ctrl[k]
        if ops[k] == 1:
            x.ctrl(q[c], q[nt + qa[k]])
        else:
            a_ = nt + qa[k]
            b_ = nt + qb[k]
            x.ctrl(q[b_], q[a_])                   # Fredkin = CNOT(b,a) . Toffoli(c,a -> b) . CNOT(b,a)
            # Toffoli(c, a -> b): standard 6-CNOT / 7-T decomposition, T = Rz(pi/4) and T^dagger = Rz(-pi/4) up to a global
            # phase (these gates are never controlled, so the circuit is unchanged); written as rz so that a noise
            # model can be attached (CUDA-Q 0.16 accepts no channel on 'tdg' and applies none to t.adj)
            h(q[b_]); x.ctrl(q[a_], q[b_]); rz(-np.pi / 4, q[b_]); x.ctrl(q[c], q[b_]); rz(np.pi / 4, q[b_])
            x.ctrl(q[a_], q[b_]); rz(-np.pi / 4, q[b_]); x.ctrl(q[c], q[b_]); rz(np.pi / 4, q[a_]); rz(np.pi / 4, q[b_]); h(q[b_])
            x.ctrl(q[c], q[a_]); rz(np.pi / 4, q[c]); rz(-np.pi / 4, q[a_]); x.ctrl(q[c], q[a_])
            x.ctrl(q[b_], q[a_])
    # inverse QFT on the counting register (same structure as the notebook: SWAPs, then H and controlled phases)
    for j in range(nt // 2):
        x.ctrl(q[j], q[nt - 1 - j]); x.ctrl(q[nt - 1 - j], q[j]); x.ctrl(q[j], q[nt - 1 - j])
    for jj in range(nt):
        j = nt - 1 - jj
        for kk in range(nt - 1 - j):
            k = nt - 1 - kk
            r1.ctrl(-np.pi / 2 ** (k - j), q[k], q[j])
        h(q[j])
    rx(idle, q[0])                                 # identity (idle = 0.0) - keeps the register size explicit


def program(a, t):
    ops, ctrl, qa, qb = [], [], [], []
    for j in range(t):
        c = pow(a, 2 ** j, 15)
        if c == 1:
            continue
        for g in mult_gates(c):
            ops.append(0 if g[0] == "swap" else 1); ctrl.append(t - 1 - j); qa.append(g[1]); qb.append(g[2] if g[0] == "swap" else 0)
    return ops, ctrl, qa, qb


def counting_dist(psi_or_rho, t, is_rho=False):
    probs = np.real(np.diag(psi_or_rho)) if is_rho else np.abs(psi_or_rho) ** 2
    out = np.zeros(2 ** t)
    for idx in np.flatnonzero(probs > 1e-15):
        y = sum(((idx >> i) & 1) << (t - 1 - i) for i in range(t))
        out[y] += probs[idx]
    return out


