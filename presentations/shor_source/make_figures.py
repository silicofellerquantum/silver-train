def candidate_orders(y, t, modulus, a):
    """Copy of the notebook's post-processing: continued-fraction denominator and its smallest valid multiple."""
    if y == 0:
        return None, []
    fraction = Fraction(y, 2 ** t).limit_denominator(modulus)
    base = fraction.denominator
    return fraction, [base * k for k in range(1, modulus // base + 1) if pow(a, base * k, modulus) == 1][:1]


def factors_from(y, t, modulus, a):
    fraction, orders = candidate_orders(y, t, modulus, a)
    if orders and orders[0] % 2 == 0 and pow(a, orders[0] // 2, modulus) != modulus - 1:
        x = pow(a, orders[0] // 2, modulus)
        p, q = math.gcd(x - 1, modulus), math.gcd(x + 1, modulus)
        if 1 < p < modulus and p * q == modulus:
            return fraction, orders[0], (min(p, q), max(p, q))
    return fraction, (orders[0] if orders else None), None


def order(a, m):
    r, v = 1, a % m
    while v != 1:
        v, r = v * a % m, r + 1
    return r


def exact_distribution(N_, a, t, n):
    """Probabilities of the counting-register value y (qubit 0 = most significant bit), from the exact state."""
    k, _ = build_state_kernel(a, modulus=N_, count_qubits=t, work_qubits=n)
    psi = np.array(cudaq.get_state(k))
    probs = np.abs(psi) ** 2
    out = np.zeros(2 ** t)
    for idx in np.flatnonzero(probs > 1e-14):
        y = sum(((idx >> i) & 1) << (t - 1 - i) for i in range(t))   # CUDA-Q index: qubit 0 = least significant bit
        out[y] += probs[idx]
    return out


