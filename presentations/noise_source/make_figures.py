# ---- 2f. dynamical decoupling: quasi-static detuning, free evolution vs Hahn echo --------------------------------
@cudaq.kernel
def ramsey(phi: float):
    q = cudaq.qvector(1)
    h(q[0]); rz(phi, q[0])


@cudaq.kernel
def echo(phi: float):
    q = cudaq.qvector(1)
    h(q[0]); rz(phi / 2, q[0]); x(q[0]); rz(phi / 2, q[0]); x(q[0])


