def build_noise_model(kind, p):
    model = cudaq.NoiseModel()
    if p == 0.0:
        return model
    if kind == "depolarizing":
        one, two = cudaq.DepolarizationChannel(p), cudaq.Depolarization2(p)
    elif kind == "bit_flip":
        probs = [0.0] * 15
        probs[0] = probs[3] = p * (1 - p)
        probs[4] = p * p
        one, two = cudaq.BitFlipChannel(p), cudaq.Pauli2(probs)
    elif kind == "phase_flip":
        probs = [0.0] * 15
        probs[2] = probs[11] = p * (1 - p)
        probs[14] = p * p
        one, two = cudaq.PhaseFlipChannel(p), cudaq.Pauli2(probs)
    else:
        k0 = np.array([[1, 0], [0, np.sqrt(1 - p)]], dtype=complex)
        k1 = np.array([[0, np.sqrt(p)], [0, 0]], dtype=complex)
        one = cudaq.AmplitudeDampingChannel(p)
        two = cudaq.KrausChannel([np.kron(a, b) for a in (k0, k1) for b in (k0, k1)])
    for gate in ("h", "x", "ry", "rz"):
        model.add_all_qubit_channel(gate, one)
    model.add_all_qubit_channel("x", two, num_controls=1)
    return model


@cudaq.kernel
def ghz_state(n: int):
    qubits = cudaq.qvector(n)
    h(qubits[0])
    for i in range(n - 1):
        x.ctrl(qubits[i], qubits[i + 1])


@cudaq.kernel
def ghz_z(n: int):
    qubits = cudaq.qvector(n)
    h(qubits[0])
    for i in range(n - 1):
        x.ctrl(qubits[i], qubits[i + 1])
    mz(qubits)


@cudaq.kernel
def ghz_x_state(n: int):
    qubits = cudaq.qvector(n)
    h(qubits[0])
    for i in range(n - 1):
        x.ctrl(qubits[i], qubits[i + 1])
    h(qubits)


@cudaq.kernel
def ghz_x(n: int):
    qubits = cudaq.qvector(n)
    h(qubits[0])
    for i in range(n - 1):
        x.ctrl(qubits[i], qubits[i + 1])
    h(qubits)
    mz(qubits)


@cudaq.kernel
def mirror_state(n: int, layers: int, angles: list[float]):
    qubits = cudaq.qvector(n)
    for layer in range(layers):
        for q in range(n):
            ry(angles[2 * (layer * n + q)], qubits[q])
            rz(angles[2 * (layer * n + q) + 1], qubits[q])
        for q in range(n - 1):
            x.ctrl(qubits[q], qubits[q + 1])
    for back in range(layers):
        layer = layers - 1 - back
        for qq in range(n - 1):
            q = n - 2 - qq
            x.ctrl(qubits[q], qubits[q + 1])
        for q in range(n):
            rz(-angles[2 * (layer * n + q) + 1], qubits[q])
            ry(-angles[2 * (layer * n + q)], qubits[q])


def hellinger(p_dist, counts, shots):
    return sum(np.sqrt(px * counts.get(x, 0) / shots) for x, px in p_dist.items()) ** 2


def parity(counts, shots):
    return sum((1 if b.count("1") % 2 == 0 else -1) * c for b, c in counts.items()) / shots


def no_error_probability(kind, p, g1, g2):
    p2 = p if kind == "depolarizing" else 1 - (1 - p) ** 2
    return (1 - p) ** g1 * (1 - p2) ** g2


