# ---- 2b. T1 / T2 relaxation from repeated amplitude + phase damping steps ----------------------------------------
@cudaq.kernel
def idle_chain(prep_plus: int, steps: int, idle: float):
    q = cudaq.qvector(1)
    if prep_plus == 1:
        h(q[0])
    else:
        x(q[0])
    for k in range(steps):
        rx(idle, q[0])


T1, T2, DT = 100.0, 80.0, 5.0                       # microseconds
gamma = 1 - np.exp(-DT / T1)
TPHI = 1 / (1 / T2 - 1 / (2 * T1))
lam = 1 - np.exp(-2 * DT / TPHI)                     # phase-damping parameter: coherence factor sqrt(1-lam) = e^{-dt/Tphi}
AD = kraus_1("amplitude_damping", gamma)
PD = [np.diag([1, np.sqrt(1 - lam)]).astype(complex), np.diag([0, np.sqrt(lam)]).astype(complex)]
TR = [a @ b for a in AD for b in PD]                 # thermal relaxation (T = 0) per step
nm_tr = cudaq.NoiseModel(); nm_tr.add_all_qubit_channel("rx", cudaq.KrausChannel(TR))
steps = np.arange(0, 41, 4)
p1, coh = [], []
for s in steps:
    p1.append(np.real(dm(idle_chain, nm_tr, 0, int(s), 0.0)[1, 1]))
    rho = dm(idle_chain, nm_tr, 1, int(s), 0.0)
    coh.append(abs(rho[0, 1]))
tt = steps * DT
t1_err = max(abs(np.array(p1) - np.exp(-tt / T1)))
t2_err = max(abs(np.array(coh) - 0.5 * np.exp(-tt / T2)))
num("tonecheck", f"{max(t1_err, t2_err):.1e}"); num("tphi", f"{TPHI:.1f}")
fig, ax = plt.subplots(figsize=(5.4, 2.6))
tf = np.linspace(0, tt[-1], 200)
ax.plot(tf, np.exp(-tf / T1), color=BLUE, lw=1.2, label=r"$e^{-t/T_1}$")
ax.plot(tt, p1, "o", color=BLUE, ms=4, label=r"$P(1)$ from $|1\rangle$ (CUDA-Q, density matrix)")
ax.plot(tf, np.exp(-tf / T2), color=ORANGE, lw=1.2, label=r"$e^{-t/T_2}$")
ax.plot(tt, 2 * np.array(coh), "s", color=ORANGE, ms=4, label=r"$2|\rho_{01}|$ from $|+\rangle$")
ax.set_xlabel(r"idle time $t$ ($\mu$s)"); ax.set_ylabel("population / coherence")
