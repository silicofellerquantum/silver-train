def dm(kernel, model, *args):
    cudaq.set_noise(model)
    try:
        return np.array(cudaq.get_state(kernel, *args))
    finally:
        cudaq.unset_noise()


def ghz_fid(rho):
    d = rho.shape[0]
    return float(0.5 * np.real(rho[0, 0] + rho[d - 1, d - 1] + rho[0, d - 1] + rho[d - 1, 0]))


def purity(rho):
    return float(np.real(np.trace(rho @ rho)))


# independent NumPy simulator (qubit 0 = most significant bit; GHZ quantities are symmetric under bit reversal)
I2 = np.eye(2, dtype=complex)
PX = np.array([[0, 1], [1, 0]], complex); PY = np.array([[0, -1j], [1j, 0]]); PZ = np.diag([1.0 + 0j, -1])
H1 = np.array([[1, 1], [1, -1]], complex) / np.sqrt(2)
PAULI = [I2, PX, PY, PZ]


def kraus_1(kind, p):
    if kind == "depolarizing":
        return [np.sqrt(1 - p) * I2] + [np.sqrt(p / 3) * P for P in (PX, PY, PZ)]
    if kind == "bit_flip":
        return [np.sqrt(1 - p) * I2, np.sqrt(p) * PX]
    if kind == "phase_flip":
        return [np.sqrt(1 - p) * I2, np.sqrt(p) * PZ]
    return [np.array([[1, 0], [0, np.sqrt(1 - p)]], complex), np.array([[0, np.sqrt(p)], [0, 0]], complex)]


def kraus_2(kind, p):
    if kind == "depolarizing":
        ops = [np.sqrt(1 - p) * np.kron(I2, I2)]
        ops += [np.sqrt(p / 15) * np.kron(PAULI[a], PAULI[b]) for a in range(4) for b in range(4) if (a, b) != (0, 0)]
        return ops
    k = kraus_1(kind, p)
    return [np.kron(a, b) for a in k for b in k]


def op_on(n, ops_by_qubit):
    out = np.array([[1.0 + 0j]])
    for q in range(n):
        out = np.kron(out, ops_by_qubit.get(q, I2))
    return out


def apply_unitary(rho, U):
    return U @ rho @ U.conj().T


def apply_channel(rho, n, qubits, kraus):
    out = np.zeros_like(rho)
    for K in kraus:
        if len(qubits) == 1:
            F = op_on(n, {qubits[0]: K})
        else:
            # two-qubit operator on adjacent qubits (c, c+1)
            c = qubits[0]
            F = np.kron(np.kron(np.eye(2 ** c), K), np.eye(2 ** (n - c - 2)))
        out += F @ rho @ F.conj().T
    return out


def cnot_adj(n, c):
    CN = np.kron(np.diag([1, 0]), I2) + np.kron(np.diag([0, 1]), PX)
    return np.kron(np.kron(np.eye(2 ** c), CN), np.eye(2 ** (n - c - 2)))


def np_ghz(n, kind, p):
    rho = np.zeros((2 ** n, 2 ** n), complex); rho[0, 0] = 1
    rho = apply_unitary(rho, op_on(n, {0: H1})); rho = apply_channel(rho, n, [0], kraus_1(kind, p))
    for i in range(n - 1):
        rho = apply_unitary(rho, cnot_adj(n, i)); rho = apply_channel(rho, n, [i, i + 1], kraus_2(kind, p))
    return rho


