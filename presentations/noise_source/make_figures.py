# ---- 2h. noise on other algorithms: QFT, QAOA, VQE (small instances, density matrix) ---------------------------
@cudaq.kernel
def qft_basis(n: int, xval: int):
    q = cudaq.qvector(n)
    for i in range(n):                               # prepare |x>, qubit 0 = most significant bit
        if (xval >> (n - 1 - i)) & 1 == 1:
            x(q[i])
    for i in range(n):
        h(q[i])
        for j in range(i + 1, n):
            r1.ctrl(np.pi / (2 ** (j - i)), q[j], q[i])


def model_qft(p):
    m = cudaq.NoiseModel()
    if p > 0:
        m.add_all_qubit_channel("h", cudaq.DepolarizationChannel(p))
        m.add_all_qubit_channel("r1", cudaq.Depolarization2(p), num_controls=1)
    return m


@cudaq.kernel
def qaoa_ring(n: int, gamma: float, beta: float):
    q = cudaq.qvector(n)
    h(q)
    for i in range(n):
        x.ctrl(q[i], q[(i + 1) % n]); rz(gamma, q[(i + 1) % n]); x.ctrl(q[i], q[(i + 1) % n])
    for i in range(n):
        rx(2.0 * beta, q[i])


@cudaq.kernel
def hea(n: int, theta: list[float]):
    q = cudaq.qvector(n)
    for i in range(n):
        ry(theta[i], q[i])
    for layer in range(2):
        for i in range(n - 1):
            x.ctrl(q[i], q[i + 1])
        for i in range(n):
            ry(theta[n * (layer + 1) + i], q[i])


def gate_noise(p):
    m = cudaq.NoiseModel()
    if p > 0:
        for g in ("h", "rz", "rx", "ry", "x"):
            m.add_all_qubit_channel(g, cudaq.DepolarizationChannel(p))
        m.add_all_qubit_channel("x", cudaq.Depolarization2(p), num_controls=1)
    return m


