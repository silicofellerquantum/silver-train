# ---- 2g. the 3-qubit bit-flip code -----------------------------------------------------------------------------
@cudaq.kernel
def bitflip_code(logical: int, idle: float):
    q = cudaq.qvector(3)
    if logical == 1:
        x(q[0])
    x.ctrl(q[0], q[1]); x.ctrl(q[0], q[2])          # encode a|000> + b|111>
    rx(idle, q[0]); rx(idle, q[1]); rx(idle, q[2])  # noise location: bit flip on every qubit
    x.ctrl(q[0], q[1]); x.ctrl(q[0], q[2])          # decode: syndrome now on q1, q2
    x.ctrl(q[1], q[2], q[0])                        # Toffoli: correct q0 if both syndrome bits are 1


@cudaq.kernel
def bare_qubit(logical: int, idle: float):
    q = cudaq.qvector(1)
    if logical == 1:
        x(q[0])
    rx(idle, q[0])


