# ---- 2a. single-qubit channels on the Bloch sphere (x-z plane), cross-checked with CUDA-Q --------------------------
@cudaq.kernel
def bloch_prep(theta: float, idle: float):
    q = cudaq.qvector(1)
    ry(theta, q[0])
    rx(idle, q[0])                         # identity gate (idle = 0.0 passed at run time) that carries the channel


CHANNELS = [("bit flip", cudaq.BitFlipChannel, "bf"), ("phase flip", cudaq.PhaseFlipChannel, "pf"),
            ("bit-phase flip", cudaq.YError, "y"), ("depolarizing", cudaq.DepolarizationChannel, "dep"),
            ("amplitude damping", cudaq.AmplitudeDampingChannel, "ad"), ("phase damping", cudaq.PhaseDamping, "pd")]


def np_kraus(code, p):
    return {"bf": [np.sqrt(1 - p) * I2, np.sqrt(p) * PX], "pf": [np.sqrt(1 - p) * I2, np.sqrt(p) * PZ],
            "y": [np.sqrt(1 - p) * I2, np.sqrt(p) * PY], "dep": kraus_1("depolarizing", p),
            "ad": kraus_1("amplitude_damping", p),
            "pd": [np.diag([1, np.sqrt(1 - p)]).astype(complex), np.diag([0, np.sqrt(p)]).astype(complex)]}[code]


def bloch(rho):
    return np.array([np.real(np.trace(rho @ P)) for P in (PX, PY, PZ)])


