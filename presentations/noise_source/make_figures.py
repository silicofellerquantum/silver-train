@cudaq.kernel
def idle_plus(steps: int, echo_mid: int, idle: float):
    q = cudaq.qvector(1)
    h(q[0])
    for k in range(steps):
        if echo_mid == 1 and k == steps // 2:
            x(q[0])
        rx(idle, q[0])
    if echo_mid == 1:
        x(q[0])


